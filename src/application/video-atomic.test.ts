import { expect, it } from 'vitest';
import { IDBFactory, IDBKeyRange } from 'fake-indexeddb';
import { createCampaignRun, createCampaignCodec } from './campaign.ts';
import { evaluateCommand } from '../core/commands.ts';
import { IndexedDbRunStore } from '../persistence/indexeddb.ts';
import { RunSession } from './session.ts';
import { MemoryWriterAccess } from '../testing/memory-writer-access.ts';
import { abortAfterHeadWrite } from '../testing/abort-after-write.ts';
import { hashValue } from '../core/hash.ts';
it('never publishes a video job, AP, cash cost or frozen fact until the atomic save commits', async () => {
    const codec = createCampaignCodec();
    let run = createCampaignRun({ runId: 'video-atomic', actorId: 'player', commandId: 'create', backgroundId: 'technical_employee', seed: 'video-atomic-seed' });
    const open = evaluateCommand(run, { runId: run.runId, actorId: 'player', commandId: 'open', expectedRevision: run.revision, kind: 'OpenVideoChannel', payload: { name: '原子保存账号', segment: 'ai_learners' } }, codec.registry, 'player');
    if (open.status !== 'proposed')
        throw new Error(JSON.stringify(open));
    run = open.nextRun;
    const factory = new IDBFactory(), name = 't10-atomic-video', store = new IndexedDbRunStore({ factory, keyRange: IDBKeyRange, name, codec });
    await store.importSave(codec.export(run), { mode: 'create', actorId: 'player', importId: 'video-start' });
    const fault = abortAfterHeadWrite(factory, name), failing = new IndexedDbRunStore({ factory: fault.factory, keyRange: IDBKeyRange, name, codec }), session = await RunSession.open({ store: failing, codec, registry: codec.registry, locks: new MemoryWriterAccess(), runId: run.runId, actorId: 'player' });
    const command = { runId: run.runId, actorId: 'player', commandId: 'video-job', expectedRevision: run.revision, kind: 'StartVideoWork', payload: { channelId: run.video!.channels[0]!.id, productId: 'hotspot', modeId: 'manual', materialId: 'original', resources: ['player-production'], startAt: '2020-01-01' } };
    expect((await session.submit(command)).status).toBe('unsaved');
    expect(session.view.features.video).toMatchObject({ works: [] });
    expect(session.view.budget.spent).toBe(0);
    expect((await store.load(run.runId))?.run).toEqual(run);
    const candidate = session.exportCandidate(), candidateHash = hashValue(candidate);
    expect(codec.import(candidate).video!.works).toHaveLength(1);
    expect((await session.retry()).status).toBe('saved');
    expect(hashValue(session.exportSaved())).toBe(candidateHash);
    expect((await session.submit(command)).status).toBe('duplicate');
    expect(session.view.budget.spent).toBe(1);
    await session.close();
    await failing.close();
    await store.close();
}, 20000);
import { replayVideoF02 } from '../testing/video-scenarios.ts';
it('does not expose a commission collection or paid case while its head transaction is aborted', async () => {
    const scenario = replayVideoF02(), run = scenario.beforeFirstCollection!, codec = scenario.f.codec, c = run.video!.contracts[0]!, factory = new IDBFactory(), name = 't10-video-collection', store = new IndexedDbRunStore({ factory, keyRange: IDBKeyRange, name, codec });
    expect(c.status).toBe('delivered');
    await store.importSave(codec.export(run), { mode: 'create', actorId: 'player', importId: 'before-collection' });
    const fault = abortAfterHeadWrite(factory, name), failing = new IndexedDbRunStore({ factory: fault.factory, keyRange: IDBKeyRange, name, codec }), session = await RunSession.open({ store: failing, codec, registry: codec.registry, locks: new MemoryWriterAccess(), runId: run.runId, actorId: 'player' }), cash = session.view.accounts[0]!.cashFen;
    const command = { runId: run.runId, actorId: 'player', commandId: 'collect-video', expectedRevision: run.revision, kind: 'AdvanceTime', payload: { date: c.paymentAt } };
    expect((await session.submit(command)).status).toBe('unsaved');
    expect(session.view.accounts[0]!.cashFen).toBe(cash);
    expect((await store.load(run.runId))!.run.video!.contracts[0]!.status).toBe('delivered');
    const candidate = session.exportCandidate();
    expect(codec.import(candidate).video!.contracts[0]!.status).toBe('settled');
    expect((await session.retry()).status).toBe('saved');
    expect(session.exportSaved()).toBe(candidate);
    expect(session.view.accounts[0]!.cashFen).toBe(cash + c.priceFen - 15000);
    expect((await session.submit(command)).status).toBe('duplicate');
    await session.close();
    await failing.close();
    await store.close();
}, 30000);
